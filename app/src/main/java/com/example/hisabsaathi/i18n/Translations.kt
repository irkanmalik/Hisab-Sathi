    fun get(key: String, language: AppLanguage): String {
        val map = when (language) {
            AppLanguage.HINDI -> hi
            AppLanguage.URDU -> ur
            AppLanguage.BENGALI, AppLanguage.MARATHI, AppLanguage.GUJARATI,
            AppLanguage.PUNJABI, AppLanguage.TAMIL, AppLanguage.TELUGU,
            AppLanguage.KANNADA, AppLanguage.MALAYALAM, AppLanguage.ODIA -> {
                // Fall back to Hindi or English for Indian regional languages while retaining language key identity
                hi
            }
            AppLanguage.ENGLISH -> en
        }
        return map[key] ?: en[key] ?: key
    }
